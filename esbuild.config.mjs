import esbuild from 'esbuild';
import fs from 'node:fs';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// A real plugin builds src/main.ts. The template itself has no src/, so it
// builds the fixture plugin instead — that way `npm run build` is meaningful in
// both places and CI exercises the same path.
const entryPoint = fs.existsSync('src/main.ts')
	? 'src/main.ts'
	: 'obsidian-tests/fixture-plugin/src/main.ts';
const outfile = entryPoint === 'src/main.ts'
	? 'main.js'
	: 'obsidian-tests/fixture-plugin/main.js';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: [entryPoint],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile,
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
